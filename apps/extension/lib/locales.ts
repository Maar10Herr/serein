export type Locale = keyof typeof messages;
export type MessageKey = keyof typeof messages.en;

/** Translate a catalog key, falling back to English for unknown locales. */
export function t(
  locale: Locale | string,
  key: MessageKey,
  values?: Readonly<Record<string, string | number>>,
): string {
  const normalizedLocale = locale.toLowerCase().replace(/_/gu, "-");
  const language = normalizedLocale.startsWith("zh")
    ? ("zh-CN" as const)
    : (normalizedLocale.split("-", 1)[0] as Locale);
  let message = messages[language]?.[key] ?? messages.en[key];

  if (values) {
    for (const [name, value] of Object.entries(values)) {
      message = message.split(`{${name}}`).join(String(value));
    }
  }

  return message;
}
